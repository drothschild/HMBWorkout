#!/usr/bin/env node
/**
 * Builds src/state/exerciseCatalogData.ts from yuhonas/free-exercise-db at a
 * PINNED commit, trimmed to the fields exercise-image matching needs (#335).
 *
 *   node scripts/build-exercise-catalog.mjs          # (re)write the data module
 *   node scripts/build-exercise-catalog.mjs --check  # exit 1 if the committed file differs
 *
 * This script is the source of every quantitative claim about the catalog
 * (entry count, dropped entries, byte size) — re-run it rather than copying a
 * number into prose. The commit below must match FREE_EXERCISE_DB_COMMIT in
 * src/state/exerciseCatalog.ts; exerciseCatalog.test.ts enforces that.
 */
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const COMMIT = 'a859101d633a01c4a1a920d6a8ce41dabba0705f';
const SOURCE_URL = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${COMMIT}/dist/exercises.json`;
const OUT_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'state',
  'exerciseCatalogData.ts'
);

function trimEntry(entry) {
  // Key order is fixed here so the output is byte-stable across runs.
  return {
    id: entry.id,
    name: entry.name,
    category: entry.category,
    equipment: entry.equipment ?? null,
    primaryMuscles: Array.isArray(entry.primaryMuscles) ? entry.primaryMuscles : [],
    image: entry.images[0],
  };
}

function render(entries, sourceCount) {
  return [
    '// pattern: Functional Core',
    '// GENERATED by scripts/build-exercise-catalog.mjs — do not edit by hand.',
    `// Source: yuhonas/free-exercise-db@${COMMIT} dist/exercises.json`,
    `// ${entries.length} of ${sourceCount} entries (entries with no image are dropped).`,
    "import type { CatalogEntry } from './exerciseCatalog';",
    '',
    'export const EXERCISE_CATALOG_DATA: readonly CatalogEntry[] = [',
    ...entries.map((entry) => `  ${JSON.stringify(entry)},`),
    '];',
    '',
  ].join('\n');
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  console.error(`fetch failed: HTTP ${response.status} for ${SOURCE_URL}`);
  process.exit(1);
}
const source = await response.json();
const entries = source
  .filter((entry) => Array.isArray(entry.images) && entry.images.length > 0)
  .map(trimEntry);
const text = render(entries, source.length);

if (process.argv.includes('--check')) {
  const committed = readFileSync(OUT_PATH, 'utf8');
  if (committed !== text) {
    console.error('exerciseCatalogData.ts differs from a fresh build — re-run without --check');
    process.exit(1);
  }
  console.log(`OK: committed catalog matches a fresh build (${entries.length} entries)`);
} else {
  writeFileSync(OUT_PATH, text);
  console.log(
    `wrote ${OUT_PATH}: ${entries.length} of ${source.length} entries, ` +
      `${Buffer.byteLength(text, 'utf8')} bytes`
  );
}
